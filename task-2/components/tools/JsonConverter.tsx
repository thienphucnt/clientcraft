export function JsonConverter() {
  const [jsonInput, setJsonInput] = useState<string>(SAMPLE_PAYLOADS.userProfile);
  const [rootName, setRootName] = useState<string>("UserProfile");
  const [useTypeAlias, setUseTypeAlias] = useState<boolean>(false);
  const [optionalFields, setOptionalFields] = useState<boolean>(false);
  const [detectDates, setDetectDates] = useState<boolean>(true);
  const [viewMode, setViewMode] = useState<"ts" | "zod" | "split">("split");
  const [copiedTs, setCopiedTs] = useState<boolean>(false);
  const [copiedZod, setCopiedZod] = useState<boolean>(false);

  // Conversion result
  const result = useMemo(() => {
    return convertJsonToTsAndZod(jsonInput, {
      rootName,
      useTypeAlias,
      optionalFields,
      detectIsoDates: detectDates,
      exportKeywords: true,
    });
  }, [jsonInput, rootName, useTypeAlias, optionalFields, detectDates]);

  // Syntax validation
  const validation = useMemo(() => {
    if (!jsonInput.trim()) return { valid: false, error: "Empty input" };
    try {
      JSON.parse(jsonInput);
      return { valid: true, error: null };
    } catch (err) {
      return {
        valid: false,
        error: err instanceof Error ? err.message : "Syntax Error in JSON",
      };
    }
  }, [jsonInput]);

  const handleFormatJson = () => {
    try {
      const parsed = JSON.parse(jsonInput);
      setJsonInput(JSON.stringify(parsed, null, 2));
    } catch {
      // Ignore
    }
  };

  const handleMinifyJson = () => {
    try {
      const parsed = JSON.parse(jsonInput);
      setJsonInput(JSON.stringify(parsed));
    } catch {
      // Ignore
    }
  };

  const copyToClipboard = async (text: string, type: "ts" | "zod") => {
    try {
      await navigator.clipboard.writeText(text);
      trackPrivacyEvent("json_converted", { format: type });
      if (type === "ts") {
        setCopiedTs(true);
        setTimeout(() => setCopiedTs(false), 2000);
      } else {
        setCopiedZod(true);
        setTimeout(() => setCopiedZod(false), 2000);
      }
    } catch {
      // Ignore
    }
  };

  const handleDownloadCode = () => {
    trackPrivacyEvent("json_converted", { format: "file_download" });
    const content = `// Generated by ClientCraft 100% In-Memory Converter\n\n${result.zod}\n\n${result.typescript}`;
    const blob = new Blob([content], { type: "text/typescript;charset=utf-8" });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = `${rootName || "schema"}.ts`;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
  };

  return (
    <div className="space-y-6">
      {/* Header & Options */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4 pb-4 border-b border-slate-200/80 dark:border-slate-800/80">
        <div>
          <h2 className="text-xl font-bold tracking-tight text-slate-900 dark:text-white flex items-center gap-2">
            <Code2 className="w-5 h-5 text-indigo-500" />
            JSON to TypeScript &amp; Zod Schema
          </h2>
          <p className="text-sm text-slate-500 dark:text-slate-400 mt-1">
            Real-time dual-pane AST type generator. Generates recursive TypeScript interfaces and Zod schemas in-memory.
          </p>
        </div>

        {/* Sample Payload Selectors */}
        <div className="flex flex-wrap items-center gap-2">
          <span className="text-xs font-medium text-slate-400">Samples:</span>
          <button
            onClick={() => {
              setJsonInput(SAMPLE_PAYLOADS.userProfile);
              setRootName("UserProfile");
            }}
            className="px-2.5 py-1 text-xs font-medium rounded-lg border border-slate-200 dark:border-slate-800 hover:bg-slate-100 dark:hover:bg-slate-900 text-slate-700 dark:text-slate-300 transition-colors"
          >
            User Profile
          </button>
          <button
            onClick={() => {
              setJsonInput(SAMPLE_PAYLOADS.ecommerceOrder);
              setRootName("OrderResponse");
            }}
            className="px-2.5 py-1 text-xs font-medium rounded-lg border border-slate-200 dark:border-slate-800 hover:bg-slate-100 dark:hover:bg-slate-900 text-slate-700 dark:text-slate-300 transition-colors"
          >
            E-Commerce Order
          </button>
          <button
            onClick={() => {
              setJsonInput(SAMPLE_PAYLOADS.apiResponse);
              setRootName("ApiResponse");
            }}
            className="px-2.5 py-1 text-xs font-medium rounded-lg border border-slate-200 dark:border-slate-800 hover:bg-slate-100 dark:hover:bg-slate-900 text-slate-700 dark:text-slate-300 transition-colors"
          >
            Paginated API
          </button>
        </div>
      </div>

      {/* Configuration Ribbon */}
      <div className="bg-white dark:bg-slate-900/60 border border-slate-200 dark:border-slate-800 rounded-2xl p-4 flex flex-wrap items-center justify-between gap-4">
        {/* Left: Root Name & Checkboxes */}
        <div className="flex flex-wrap items-center gap-4">
          <div className="flex items-center gap-2">
            <span className="text-xs font-semibold text-slate-600 dark:text-slate-400">Root Type:</span>
            <input
              type="text"
              value={rootName}
              onChange={(e) => setRootName(e.target.value)}
              placeholder="RootObject"
              className="text-xs font-mono font-medium px-2.5 py-1.5 rounded-lg border border-slate-300 dark:border-slate-700 bg-slate-50 dark:bg-slate-800 text-slate-900 dark:text-slate-100 focus:outline-hidden focus:ring-1 focus:ring-blue-500 w-36"
            />
          </div>

          <label className="flex items-center gap-2 text-xs text-slate-700 dark:text-slate-300 cursor-pointer">
            <input
              type="checkbox"
              checked={optionalFields}
              onChange={(e) => setOptionalFields(e.target.checked)}
              className="rounded-sm accent-blue-600 w-3.5 h-3.5 cursor-pointer"
            />
            <span>Optional Fields (?)</span>
          </label>

          <label className="flex items-center gap-2 text-xs text-slate-700 dark:text-slate-300 cursor-pointer">
            <input
              type="checkbox"
              checked={detectDates}
              onChange={(e) => setDetectDates(e.target.checked)}
              className="rounded-sm accent-blue-600 w-3.5 h-3.5 cursor-pointer"
            />
            <span>ISO Dates Detection</span>
          </label>

          <label className="flex items-center gap-2 text-xs text-slate-700 dark:text-slate-300 cursor-pointer">
            <input
              type="checkbox"
              checked={useTypeAlias}
              onChange={(e) => setUseTypeAlias(e.target.checked)}
              className="rounded-sm accent-blue-600 w-3.5 h-3.5 cursor-pointer"
            />
            <span>Use Type Alias</span>
          </label>
        </div>

        {/* Right: View Mode Toggle */}
        <div className="flex items-center gap-1.5 bg-slate-100 dark:bg-slate-800/80 p-1 rounded-xl border border-slate-200 dark:border-slate-700/60">
          <button
            onClick={() => setViewMode("split")}
            className={`px-2.5 py-1 rounded-lg text-xs font-medium transition-all ${
              viewMode === "split"
                ? "bg-white dark:bg-slate-700 text-slate-900 dark:text-white shadow-xs"
                : "text-slate-500 hover:text-slate-900 dark:text-slate-400 dark:hover:text-white"
            }`}
          >
            Split View
          </button>
          <button
            onClick={() => setViewMode("ts")}
            className={`px-2.5 py-1 rounded-lg text-xs font-medium transition-all ${
              viewMode === "ts"
                ? "bg-white dark:bg-slate-700 text-slate-900 dark:text-white shadow-xs"
                : "text-slate-500 hover:text-slate-900 dark:text-slate-400 dark:hover:text-white"
            }`}
          >
            TypeScript Only
          </button>
          <button
            onClick={() => setViewMode("zod")}
            className={`px-2.5 py-1 rounded-lg text-xs font-medium transition-all ${
              viewMode === "zod"
                ? "bg-white dark:bg-slate-700 text-slate-900 dark:text-white shadow-xs"
                : "text-slate-500 hover:text-slate-900 dark:text-slate-400 dark:hover:text-white"
            }`}
          >
            Zod Only
          </button>
        </div>
      </div>

      {/* Dual Pane Layout */}
      <div className="grid grid-cols-1 lg:grid-cols-12 gap-6">
        {/* Left Editor: JSON Input */}
        <div className="lg:col-span-5 flex flex-col space-y-3">
          <div className="flex items-center justify-between">
            <div className="flex items-center gap-2">
              <span className="text-xs font-bold uppercase tracking-wider text-slate-500 dark:text-slate-400">
                Raw JSON Input
              </span>
              {validation.valid ? (
                <span className="inline-flex items-center gap-1 px-2 py-0.5 rounded-full text-[10px] font-semibold bg-emerald-500/10 text-emerald-600 dark:text-emerald-400 border border-emerald-500/20">
                  <CheckCircle2 className="w-3 h-3" /> Valid JSON
                </span>
              ) : (
                <span className="inline-flex items-center gap-1 px-2 py-0.5 rounded-full text-[10px] font-semibold bg-rose-500/10 text-rose-600 dark:text-rose-400 border border-rose-500/20">
                  <AlertTriangle className="w-3 h-3" /> Invalid
                </span>
              )}
            </div>

            <div className="flex items-center gap-1">
              <button
                onClick={handleFormatJson}
                title="Format JSON"
                className="px-2 py-1 text-xs font-medium rounded-lg hover:bg-slate-100 dark:hover:bg-slate-800 text-slate-600 dark:text-slate-300 transition-colors"
              >
                Prettify
              </button>
              <button
                onClick={handleMinifyJson}
                title="Minify JSON"
                className="px-2 py-1 text-xs font-medium rounded-lg hover:bg-slate-100 dark:hover:bg-slate-800 text-slate-600 dark:text-slate-300 transition-colors"
              >
                Minify
              </button>
              <button
                onClick={() => setJsonInput("")}
                title="Clear input"
                className="px-2 py-1 text-xs font-medium rounded-lg hover:bg-slate-100 dark:hover:bg-slate-800 text-slate-400 hover:text-slate-600 transition-colors"
              >
                Clear
              </button>
            </div>
          </div>

          <div className="relative flex-1 min-h-[460px] rounded-2xl border border-slate-200 dark:border-slate-800 overflow-hidden bg-slate-900 text-slate-100 shadow-inner">
            <textarea
              value={jsonInput}
              onChange={(e) => setJsonInput(e.target.value)}
              placeholder="Paste or write raw JSON here..."
              spellCheck={false}
              className="w-full h-full p-4 font-mono text-xs leading-relaxed bg-transparent resize-none focus:outline-hidden text-emerald-400"
            />
          </div>
          {validation.error && (
            <p className="text-xs text-rose-500 font-mono bg-rose-500/10 p-2.5 rounded-xl border border-rose-500/20">
              {validation.error}
            </p>
          )}
        </div>

        {/* Right Editor: Generated TypeScript & Zod Code */}
        <div className="lg:col-span-7 flex flex-col space-y-3">
          <div className="flex items-center justify-between">
            <span className="text-xs font-bold uppercase tracking-wider text-slate-500 dark:text-slate-400">
              Generated Type Definitions
            </span>

            <div className="flex items-center gap-2">
              <button
                onClick={handleDownloadCode}
                className="flex items-center gap-1.5 px-3 py-1 rounded-xl text-xs font-medium border border-slate-200 dark:border-slate-800 hover:bg-slate-100 dark:hover:bg-slate-800 text-slate-700 dark:text-slate-200 transition-colors"
              >
                <Download className="w-3.5 h-3.5" />
                <span>Export .ts</span>
              </button>
            </div>
          </div>

          {/* Pane Container */}
          <div className="grid grid-cols-1 gap-4 flex-1">
            {/* TypeScript Pane */}
            {(viewMode === "split" || viewMode === "ts") && (
              <div className="flex flex-col rounded-2xl border border-slate-200 dark:border-slate-800 overflow-hidden bg-slate-950 text-slate-100 min-h-[220px]">
                <div className="flex items-center justify-between px-4 py-2.5 bg-slate-900/80 border-b border-slate-800">
                  <div className="flex items-center gap-2 text-xs font-semibold text-blue-400">
                    <FileCode className="w-3.5 h-3.5" />
                    <span>TypeScript Interfaces</span>
                  </div>
                  <button
                    onClick={() => copyToClipboard(result.typescript, "ts")}
                    className="flex items-center gap-1 text-[11px] font-medium text-slate-300 hover:text-white px-2 py-0.5 rounded-md hover:bg-slate-800 transition-all"
                  >
                    {copiedTs ? <Check className="w-3.5 h-3.5 text-emerald-400" /> : <Copy className="w-3.5 h-3.5" />}
                    <span>{copiedTs ? "Copied" : "Copy TS"}</span>
                  </button>
                </div>
                <pre className="p-4 font-mono text-xs leading-relaxed overflow-x-auto text-blue-200/90 whitespace-pre flex-1 max-h-[300px]">
                  <code>{result.typescript}</code>
                </pre>
              </div>
            )}

            {/* Zod Schema Pane */}
            {(viewMode === "split" || viewMode === "zod") && (
              <div className="flex flex-col rounded-2xl border border-slate-200 dark:border-slate-800 overflow-hidden bg-slate-950 text-slate-100 min-h-[220px]">
                <div className="flex items-center justify-between px-4 py-2.5 bg-slate-900/80 border-b border-slate-800">
                  <div className="flex items-center gap-2 text-xs font-semibold text-indigo-400">
                    <Code2 className="w-3.5 h-3.5" />
                    <span>Zod Validation Schemas</span>
                  </div>
                  <button
                    onClick={() => copyToClipboard(result.zod, "zod")}
                    className="flex items-center gap-1 text-[11px] font-medium text-slate-300 hover:text-white px-2 py-0.5 rounded-md hover:bg-slate-800 transition-all"
                  >
                    {copiedZod ? <Check className="w-3.5 h-3.5 text-emerald-400" /> : <Copy className="w-3.5 h-3.5" />}
                    <span>{copiedZod ? "Copied" : "Copy Zod"}</span>
                  </button>
                </div>
                <pre className="p-4 font-mono text-xs leading-relaxed overflow-x-auto text-indigo-200/90 whitespace-pre flex-1 max-h-[300px]">
                  <code>{result.zod}</code>
                </pre>
              </div>
            )}
          </div>
        </div>
      </div>
    </div>
  );
}
