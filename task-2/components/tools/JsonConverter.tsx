import {
  Code2,
  Copy,
  Check,
  Download,
  CheckCircle2,
  AlertTriangle,
  FileCode,
} from "lucide-react";
import { convertJsonToTsAndZod } from "@/lib/tools/json-to-ts-zod";
import { trackPrivacyEvent } from "@/lib/analytics";

